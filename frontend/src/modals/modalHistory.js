/**
 * Учёт записей истории браузера, которые кладут за собой модалки.
 *
 * Зачем вообще: модалка жила вне истории, и «назад» уносил человека на
 * предыдущую страницу, оставляя её висеть поверх (жалоба владельца
 * 17.09.2026). Последнее действие — открытие модалки, его «назад» и должно
 * отменять.
 *
 * Логика вынесена из ModalProvider отдельным модулем не ради красоты: она
 * держится на двух счётчиках, и ошибка в них проявляется не сразу, а на
 * второй-третьей модалке. Отдельная функция без React проверяется обычным
 * скриптом с поддельной историей (см. scratchpad/test_modal_history.mjs).
 *
 * Адрес при открытии НЕ меняется: модалка не экран, ссылку на неё не
 * пересылают, и прятать её в URL значило бы уметь восстанавливать её при
 * открытии по ссылке.
 */
export function createModalHistory(historyApi) {
  const api = historyApi ?? (typeof window !== 'undefined' ? window.history : null);

  // Сколько записей истории положили мы сами — по одной на открытую модалку.
  let pushed = 0;
  // Сколько ближайших popstate — эхо нашего же back(): стек по ним уже
  // подрезан, второй раз закрывать нечего.
  let selfBack = 0;

  return {
    /** Сколько наших записей сейчас лежит в истории. */
    get depth() {
      return pushed;
    },

    /** Модалка открылась. */
    open() {
      api?.pushState({ mlModal: true }, '');
      pushed += 1;
    },

    /**
     * Модалку закрыли крестиком, Escape или кнопкой внутри неё. Снимаем свою
     * запись: иначе в истории копились бы пустышки — человек закрыл модалку и
     * жмёт «назад», а браузер отматывает на запись с тем же адресом, и
     * визуально не происходит ничего.
     */
    close() {
      if (pushed === 0) return;
      pushed -= 1;
      selfBack += 1;
      api?.back();
    },

    /**
     * Забыть свои записи, не трогая историю. Нужно там, где модалки
     * закрывают ПЕРЕД уходом на другой экран: `back()` выполнился бы уже
     * после перехода (браузер откладывает его, а переход происходит сразу) и
     * утащил бы человека обратно. Оставшаяся запись безобидна — у неё тот же
     * адрес, что у экрана, с которого ушли.
     */
    forget() {
      pushed = 0;
    },

    /**
     * Пришёл popstate. true — это человек нажал «назад» при открытой
     * модалке, её надо закрыть; false — либо эхо нашего собственного back(),
     * либо настоящая навигация, в которую мешаться нельзя.
     */
    onPop() {
      if (selfBack > 0) {
        selfBack -= 1;
        return false;
      }
      if (pushed === 0) return false;
      pushed -= 1;
      return true;
    },
  };
}
