/**
 * Обёртка-подсказка. Теперь это лишь СЛАДКАЯ ОБЁРТКА над общим слоем
 * (`HintLayer`): рисует один `<span>` с атрибутом `data-hint`.
 *
 * Зачем она осталась, раз атрибут можно повесить на что угодно: иногда
 * подсказку надо привязать не к самому элементу, а к обёртке — например, у
 * поля ввода, которое занимает всю ячейку, или у значка, стоящего absolute.
 * Тогда удобнее обернуть, чем заводить атрибут на каждом вложенном элементе.
 *
 * Своей логики показа здесь БОЛЬШЕ НЕТ. Она была, и это стоило нам трёх
 * заходов: часть мест переводили на компонент, а часть оставалась с
 * браузерным `title`, и всякий раз находилась ветка, где всплывала
 * системная подсказка. Один слой на приложение — один способ.
 */
export function Tooltip({ text, children, className = '' }) {
  if (!text) return children;
  return (
    <span className={className} data-hint={text}>
      {children}
    </span>
  );
}
