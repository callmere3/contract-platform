/**
 * Экран, который уже нарисован, но ещё не работает.
 *
 * Такие разделы показываются намеренно: по ним видно, куда движется продукт,
 * а тому, кто откроет раздел по ошибке, сразу понятно, что делать здесь пока
 * нечего. Общий компонент появился, когда таких экранов стало два (ML Finance:
 * «Загрузка отчётов» и «Отчёты правообладателям») — иначе разметка штампа
 * разошлась бы между ними при первой же правке.
 *
 * ШТАМП СТОИТ ПОД СОДЕРЖИМЫМ, А НЕ ПОВЕРХ НЕГО. Сначала он лежал по центру
 * экрана и оказался ровно на заголовке: сам читался плохо, а текст под ним не
 * читался вовсе (16.09.2026, по скриншоту). Наложение поверх работает, когда
 * под ним фон или картинка; поверх строк текста оно съедает и то, и другое.
 *
 * «Не работает» держится на ДВУХ вещах, и это не перестраховка:
 *   - содержимое НЕ ПРИНИМАЕТ НАЖАТИЙ (`pointer-events-none`), поэтому кнопки
 *     внутри не нажимаются физически, а не только выглядят неактивными.
 *     Полагаться на `disabled` у каждой кнопки нельзя: завтра рядом появится
 *     вторая, и о ней забудут;
 *   - штамп говорит об этом словами.
 * Когда раздел заработает, компонент снимается целиком — содержимое внутри
 * уже настоящее.
 */
export function UnderConstruction({ children, note, align = 'center' }) {
  return (
    <>
      {/* Слой показа: приглушён, но читаем — он и есть то, что человек пришёл
          посмотреть.

          align — про содержимое, а не про штамп: hero-экраны («Загрузка
          отчётов», «Отчёты правообладателям») центрируются, а таблица
          номенклатуры — нет, иначе по центру уехали бы и заголовки колонок, и
          каждая ячейка. Сам штамп ниже центрируется всегда. */}
      <div
        className={`opacity-60 grayscale pointer-events-none select-none ${
          align === 'center' ? 'text-center' : 'text-left'
        }`}
      >
        {children}
      </div>

      {/* Штамп — на пустом месте под содержимым и в полную силу: он не
          декорация, а единственное, что здесь сейчас правда. Наклон и пунктир
          — чтобы читался как пометка на макете, а не как элемент интерфейса,
          который можно нажать. */}
      <div className="flex flex-col items-center gap-3 mt-14">
        <span className="-rotate-[6deg] border-2 border-dashed border-text-muted rounded-card px-6 py-2.5 text-[20px] font-extrabold tracking-[0.12em] uppercase text-text-muted">
          В разработке
        </span>
        {note && (
          <span className="text-[13px] text-text-muted max-w-[340px] text-center leading-relaxed">
            {note}
          </span>
        )}
      </div>
    </>
  );
}
