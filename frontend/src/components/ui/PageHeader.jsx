/**
 * Шапка вкладки: название и одна строка о том, что это за экран.
 *
 * ОДИН КОМПОНЕНТ НА ВСЕ ВКЛАДКИ (17.09.2026, просьба владельца: «почему на
 * контрагентах в ML Finance нет названия, а на других вкладках есть»).
 * Раньше шапка была написана руками в «Номенклатуре» и «Партнёрах», а
 * остальные экраны начинались прямо с карточки поиска — и человек, переходя
 * между вкладками, то видел, куда попал, то нет. Размеры и отступы теперь
 * живут в одном месте: разъехаться им больше негде.
 *
 * ОПИСАНИЕ — ОДНА ФРАЗА, и это не лень. Оно отвечает на вопрос «что здесь
 * можно сделать», а не пересказывает интерфейс: длинный текст над каждым
 * экраном перестают читать на третьем.
 *
 * `spaced` — отступ снизу. На страницах, собранных как колонка с `gap-6`
 * («Кубок», «Уведомления»), расстояние задаёт сам контейнер, и свой отступ
 * здесь дал бы двойной.
 *
 * Вкладки «Генерация» у шапки НЕТ намеренно: там свой крупный экран с
 * приглашением найти контрагента, и служебная строчка над ним только
 * мешала бы (решение владельца 17.09.2026).
 */
export function PageHeader({ title, children, spaced = true }) {
  return (
    <div className={spaced ? 'mb-6' : ''}>
      <h1 className="text-[26px] font-extrabold tracking-[-0.02em] text-text mb-1.5">{title}</h1>
      {children && (
        <p className="text-[13.5px] text-text-secondary max-w-[620px] leading-relaxed">
          {children}
        </p>
      )}
    </div>
  );
}
