#!/bin/bash
# Сторож api (инцидент 25.09.2026). Система убила рабочий процесс uvicorn за
# нехватку памяти, а контейнер остался «Up»: процесс-перезагрузчик
# (--reload) жив, нового рабочего сам не поднимает, и сервис висел, пока
# его не перезапустили руками.
#
# Раз в минуту (cron root'а) спрашиваем /health. Не ответил ДВАЖДЫ подряд
# по 20 секунд — трогаем main.py: --reload поднимает рабочего заново, как
# при обычном деплое. Две попытки, а не одна: тяжёлый разбор отчёта может
# задержать ответ, и перезапуск посреди загрузки отчёта хуже минуты ожидания.
# Контейнер целиком не перезапускаем — это дольше и рвёт соединения с базой.
#
# Лог — /var/log/api-watchdog.log, пишется только когда что-то сделали.
set -u
cd "$(dirname "$0")/.." || exit 1

check() { curl -s -o /dev/null -m 20 -w '%{http_code}' http://127.0.0.1:8000/health; }

[ "$(check)" = "200" ] && exit 0
sleep 5
[ "$(check)" = "200" ] && exit 0

echo "$(date -u '+%F %T') api не отвечает — перезапускаю рабочий процесс" >> /var/log/api-watchdog.log
touch backend/app/main.py
