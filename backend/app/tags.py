"""
Канонические значения тегов страна / тип контрагента / тип договора.

Используются и контрагентами (contragents.country/type/contract_family), и
шаблонами (templates.country/contragent_type/contract_family) — подбор
документов по контрагенту (шаг 4 брейншторма) сравнивает эти поля НАПРЯМУЮ,
без ILIKE. Поэтому критично, чтобы значения всегда приходили в одном и том
же регистре и написании, а не как их напечатал оператор ('ру' vs 'РУ').

COUNTRIES / CONTRAGENT_TYPES / CONTRACT_FAMILIES — единственный источник
правды для обоих мест; при добавлении нового значения (например, нового
типа договора) достаточно дополнить список здесь.
"""
from fastapi import HTTPException

COUNTRIES = ["РУ", "KZ"]
# Порядок = порядок в выпадающем списке: физлица (ФЛ/СГ/ИП), затем компании
# (ООО — РУ, ТОО — KZ).
#   ФЛ  — физлицо без самозанятости (РУ)
#   СГ  — самозанятый гражданин (РУ)
#   ИП  — индивидуальный предприниматель (РУ)
#   ООО — общество с ограниченной ответственностью (РУ)
#   ТОО — товарищество с ограниченной ответственностью (KZ, аналог ООО)
# Тип и страна независимы (плоский список): казахскую компанию оператор
# заводит как ТОО+KZ, российскую — как ООО+РУ. Жёсткой связки «ТОО только
# для KZ» нет — подбор документов и так идёт по точному совпадению тройки
# (страна, тип, тип договора), поэтому KZ+ООО просто не найдёт KZ+ТОО-шаблон.
CONTRAGENT_TYPES = ["ФЛ", "СГ", "ИП", "ООО", "ТОО"]

# Тип договора (contract_family) — это на самом деле ДВЕ независимые оси,
# слитые в одно значение:
#   - платёж:       АВАНС / РОЯЛТИ — влияет только на текст самого ДОГОВОРА;
#   - обязательство: без / с        — влияет и на договор, и на приложение/акт.
# Поэтому ДОГОВОРОВ четыре (платёж × обязательство), а вот ПРИЛОЖЕНИЯ и АКТЫ
# различаются ТОЛЬКО по обязательству: акт роялти = акт аванс, приложение
# «аванс+обязательство» = приложение «роялти+обязательство». То есть у
# приложения/акта платёжной оси нет вовсе (решение владельца 03.08.2026).
CONTRACT_FAMILIES = ["РОЯЛТИ", "АВАНС", "РОЯЛТИ_ОБЯЗАТЕЛЬСТВО", "АВАНС_ОБЯЗАТЕЛЬСТВО"]

# Приложения и акты тегируются НЕ семейством, а бакетом обязательства (2
# значения). Это отдельный справочник — намеренно не смешиваем с четырьмя
# семействами: тег приложения «БЕЗ_ОБЯЗАТЕЛЬСТВА» читается однозначно, а
# «АВАНС» на приложении, которое обслуживает и роялти, был бы миной. Подбор
# для приложения/акта идёт по этому бакету (см. list_contragent_templates и
# obligation_bucket ниже), а не по полному семейству контрагента.
OBLIGATION_SUFFIX = "_ОБЯЗАТЕЛЬСТВО"
BUCKET_WITH_OBLIGATION = "ОБЯЗАТЕЛЬСТВО"
BUCKET_WITHOUT_OBLIGATION = "БЕЗ_ОБЯЗАТЕЛЬСТВА"
OBLIGATION_BUCKETS = [BUCKET_WITHOUT_OBLIGATION, BUCKET_WITH_OBLIGATION]

# Тип документа, у которого тег — бакет обязательства, а не семейство.
OBLIGATION_DOC_TYPES = ("appendix", "act")


def obligation_bucket(contract_family: str | None) -> str:
    """
    Бакет обязательства, в который попадает семейство договора: у семейства
    с суффиксом _ОБЯЗАТЕЛЬСТВО — 'ОБЯЗАТЕЛЬСТВО', иначе 'БЕЗ_ОБЯЗАТЕЛЬСТВА'.
    По нему приложение/акт подбираются к контрагенту (его платёжная ось —
    аванс/роялти — для приложения/акта не важна).
    """
    if contract_family and contract_family.endswith(OBLIGATION_SUFFIX):
        return BUCKET_WITH_OBLIGATION
    return BUCKET_WITHOUT_OBLIGATION

# Организационная форма компании зависит от страны: в РФ это ООО, в
# Казахстане — ТОО. Отсюда фронт (GET /tags) фильтрует выпадающий список
# типов под выбранную страну: для KZ предлагается ТОО, а не ООО, и наоборот.
# Физлица (ФЛ/СГ/ИП) от страны не зависят и остаются для обеих.
#
# Это подсказка для UI, а не жёсткий запрет на бэкенде: импорт из Excel
# по-прежнему принимает любую валидную пару (см. loose-валидацию), чтобы не
# ронять загрузку из-за нестандартной строки. Несовпадение всплывёт само —
# подбор документов идёт по точной тройке тегов, и KZ+ООО не найдёт KZ+ТОО.
COMPANY_TYPE_BY_COUNTRY = {"РУ": "ООО", "KZ": "ТОО"}

# Единый рег. номер контрагента (contragents.reg_number) — смысл и ожидаемая
# длина зависят от типа контрагента. Одна и та же колонка в БД для всех типов
# (см. models.py, докстринг Contragent) — это словарь для подписи в UI и для
# валидации длины, а не отдельные поля.
#   ФЛ/СГ — ИНН физлица, 12 цифр
#   ИП    — ОГРНИП, 15
#   ООО   — ОГРН, 13
#   ТОО   — БИН (бизнес-идентификационный номер РК), 12
# ФЛ и СГ делят ИНН: у одного человека ИНН один, поэтому две его карточки
# ФЛ и СГ с ЗАПОЛНЕННЫМ ИНН одновременно не создать (reg_number UNIQUE) —
# так же, как это уже работает между любыми типами. Пустой ИНН конфликта не
# даёт (несколько NULL в unique-индексе разрешены).
REG_NUMBER_META = {
    "ФЛ": ("ИНН", 12),
    "СГ": ("ИНН", 12),
    "ИП": ("ОГРНИП", 15),
    "ООО": ("ОГРН", 13),
    "ТОО": ("БИН", 12),
}

# Каноническая метка формы, В КОТОРУЮ подставляется рег. номер карточки, —
# своя для каждого типа контрагента (см. REG_NUMBER_META). Рег. номер — одна
# колонка с разным смыслом по типу: ИНН у ФЛ/СГ, ОГРНИП у ИП, ОГРН у ООО,
# БИН у ТОО. В шаблоне ИП-договора рядом стоят ДВЕ рег-подобные метки: ogrnip
# (это и есть рег. номер) и inn (ИНН — отдельное поле реквизитов, в карточке
# НЕ хранится). С рег. номером карточки допустимо связывать только «свою»
# метку типа — этот словарь и есть источник правды, кто именно.
REG_NUMBER_MARK = {
    "ФЛ": "inn",
    "СГ": "inn",
    "ИП": "ogrnip",
    "ООО": "ogrn",
    "ТОО": "bin",
}
# Все рег-метки: любую из них связывать с contragent.reg_number можно ТОЛЬКО
# в шаблоне своего типа (см. validate_reg_number_mapping).
REG_NUMBER_MARKS = set(REG_NUMBER_MARK.values())


def validate_reg_number_mapping(
    contragent_type: str | None, placeholder: str, maps_to: str
) -> None:
    """
    Не даёт по ошибке связать maps_to='contragent.reg_number' с «чужой»
    рег-меткой (см. REG_NUMBER_MARK).

    Зачем: у ИП-договора есть И ogrnip (рег. номер = ОГРНИП), И inn (ИНН —
    только в реквизитах, в карточке его нет). Привычно связав inn с рег.
    номером (как в шаблоне СГ, где рег. номер И ЕСТЬ ИНН), админ подставил
    бы в поле ИНН чужой ОГРНИП. Ловим это здесь явной 400, а не молча.

    Срабатывает ТОЛЬКО для maps_to='contragent.reg_number' и ТОЛЬКО для
    рег-меток (inn/ogrnip/ogrn/bin) — остальные связи не трогает. Если тип
    шаблона не задан, сверять не с чем — пропускаем (связь разрешена).
    """
    if maps_to != "contragent.reg_number":
        return
    if placeholder not in REG_NUMBER_MARKS:
        return
    expected = REG_NUMBER_MARK.get(contragent_type or "")
    if expected is None or placeholder == expected:
        return
    label = REG_NUMBER_META.get(contragent_type, (placeholder, 0))[0]
    raise HTTPException(
        status_code=400,
        detail=(
            f"Для типа {contragent_type} рег. номер карточки — это {label}, "
            f"его подставляет метка {expected!r}, а не {placeholder!r}. "
            f"Метку {placeholder!r} оставьте ручной (maps_to='manual')."
        ),
    )


