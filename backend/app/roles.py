"""
Канонические роли пользователей (этап 6, брейншторм ролей).

  ADMIN        — полный доступ: пользователи и роли, шаблоны, контрагенты
                 (включая удаление), импорт/экспорт, audit_log, вся история
                 генерации.
  DIRECTOR     — как MANAGER, плюс правка карточек контрагентов, экспорт в
                 Excel, просмотр audit_log, вся история генерации и ПРОСМОТР
                 вкладки "Пользователи" (только видит список и роли — НЕ
                 создаёт, не правит, роли не меняет: это осталось за Admin).
                 НЕТ: импорта, управления шаблонами, удаления контрагентов.
  TOP_MANAGER  — как MANAGER, плюс правка карточек контрагентов и СВОЯ история
                 генерации (только свои документы). БЕЗ экспорта, без audit_log;
                 шаблоны с пометкой "скрыт" не видит.
  TESTER       — как MANAGER, плюс правка карточек контрагентов, кнопка
                 "Тестовые данные" в форме (заполнить демо-значениями в один
                 клик) и просмотр СКРЫТЫХ шаблонов — всё для обкатки шаблонов.
                 БЕЗ экспорта и без истории генерации. Кнопка демо — чисто
                 UX-ная (см. canFillDemoData в permissions.js: серверной
                 проверки нет, демо-данные не привилегия). Самостоятельная
                 роль: раньше повторяла TOP_MANAGER, теперь их права разошлись
                 (у тестера — скрытые шаблоны и демо, у топ-менеджера — своя
                 история генерации), общей зависимости между ними больше нет.
  MANAGER      — рабочая роль: генерация документов, создание контрагентов.
                 Без РЕДАКТИРОВАНИЯ уже заведённых карточек, без удаления,
                 без импорта/экспорта, без шаблонов, без audit_log.

ROLES — единственный источник правды, как COUNTRIES/CONTRAGENT_TYPES в
app/tags.py: любая новая роль добавляется здесь и сразу используется во
всех проверках require_role(...) по всему коду.

Роль хранится в users.role как обычный varchar(16) — ограничения на уровне
БД нет, проверка только здесь (_validate_role в routers_auth.py сверяет с
ROLES). Поэтому новая роль НЕ требует миграции; следить надо лишь за тем,
чтобы её строковое значение влезло в 16 символов.
"""
ADMIN = "admin"
DIRECTOR = "director"
TOP_MANAGER = "top_manager"
TESTER = "tester"
MANAGER = "manager"

ROLES = (ADMIN, DIRECTOR, TOP_MANAGER, TESTER, MANAGER)

# Общие сокращения для Depends(require_role(...)) в роутерах — чтобы не
# перечислять одни и те же тройки/пары ролей в каждом файле по-разному.
ANY_ROLE = ROLES                              # любой залогиненный пользователь
# Экспорт контрагентов и просмотр audit_log раньше делили одну константу
# (CAN_EXPORT), пока обе роли с доступом к экспорту совпадали с ролями с
# доступом к audit_log. С появлением TOP_MANAGER (экспорт есть, audit_log
# нет) это перестало быть верным — разделены на две константы.
CAN_EXPORT_CONTRAGENTS = (ADMIN, DIRECTOR)  # экспорт в Excel (у top_manager/tester убран)
CAN_VIEW_AUDIT_LOG = (ADMIN, DIRECTOR)                    # просмотр audit_log
# Доступ к вкладке "История генерации" (эндпоинты /generation-history).
# TOP_MANAGER сюда добавлен, но видит ТОЛЬКО свои документы — сервер жёстко
# ограничивает выдачу его user_id (см. SEES_ALL_GENERATION_HISTORY ниже и
# routers_generation_history.py). Разница именно в объёме: доступ к вкладке
# есть, объём — свой.
CAN_VIEW_GENERATION_HISTORY = (ADMIN, DIRECTOR, TOP_MANAGER)
# Кто видит историю ВСЕХ пользователей. Остальные из CAN_VIEW_GENERATION_HISTORY
# (сейчас только TOP_MANAGER) видят и пересоздают лишь свои записи. Ограничение
# серверное, а не UX: без него top_manager по filter_type=user или прямым
# entry_id мог бы дотянуться до чужих документов.
SEES_ALL_GENERATION_HISTORY = (ADMIN, DIRECTOR)
CAN_IMPORT = (ADMIN,)               # импорт контрагентов — только Admin
# Вкладка "Пользователи" разведена на два права:
#   VIEW   — видеть список пользователей и их роли (Admin + Director);
#   MANAGE — создавать, править, деактивировать, менять роли (только Admin).
# Director добавлен в просмотр по просьбе владельца, но роли НЕ меняет —
# управление осталось за Admin (эндпоинты create_user/update_user).
CAN_VIEW_USERS = (ADMIN, DIRECTOR)
CAN_MANAGE_USERS = (ADMIN,)
CAN_MANAGE_TEMPLATES = (ADMIN,)
CAN_DELETE_CONTRAGENTS = (ADMIN,)
# Вкладка "Уведомления": предложения дозаполнить карточку контрагента данными,
# которые менеджер вписал в форму генерации (см. app/models.py: CardSuggestion).
# Только Admin — это правка эталонных карточек: применить/отклонить чужой ввод
# может лишь тот, кто отвечает за базу. Director сюда НЕ добавлен намеренно:
# он карточки правит, но за качество базы отвечает admin (по аналогии с
# импортом/управлением пользователями — тоже только admin).
CAN_VIEW_NOTIFICATIONS = (ADMIN,)

# Генерация документов и создание контрагентов — рабочие действия, доступные
# ВСЕМ ролям, включая те, что появятся в будущем. Поэтому здесь = ROLES, а не
# перечисление поимённо.
#
# ЭТО НЕ ПРИДИРКА К СТИЛЮ. Оба кортежа раньше перечисляли роли вручную, и
# оба молча ломались при добавлении новой: TESTER 17.07.2026 не смог
# сгенерировать документ именно потому, что CAN_GENERATE перечислял четыре
# роли и про пятую не знал. Комментарий рядом при этом честно гласил
# "доступно всем ролям" — то есть намерение и код разошлись, а поймал это
# только пользователь на проде. С `= ROLES` разойтись уже нечему.
CAN_GENERATE = ROLES
CAN_CREATE_CONTRAGENTS = ROLES

# Редактирование существующей карточки — НЕ для Manager: он заводит новых
# контрагентов и генерирует по ним документы, но правка уже заведённой
# карточки (в т.ч. reg_number — точного идентификатора) остаётся за
# Admin/Director/TopManager/Tester. Здесь перечисление осмысленно: это
# именно ограниченный список, а не "все".
CAN_EDIT_CONTRAGENTS = (ADMIN, DIRECTOR, TOP_MANAGER, TESTER)

# Тип договора (contract_family) карточки может менять ЛЮБАЯ роль, включая
# manager — по просьбе владельца: менеджеру нужно уметь переключить тип
# договора контрагента (от него зависит подбор документов), но НЕ трогать
# остальные поля карточки. Поэтому эндпоинт update_contragent доступен всем
# этим ролям, но тем, кого нет в CAN_EDIT_CONTRAGENTS (сейчас — manager),
# разрешено передать ТОЛЬКО contract_family; любое другое поле → 403.
CAN_EDIT_CONTRACT_FAMILY = ROLES

# Кто видит шаблоны, помеченные "скрыт для менеджеров" (hidden_for_managers):
# admin/director/tester. У top_manager видимость скрытых убрана (по просьбе
# владельца) — по этому праву он теперь как обычный manager. Скрытие нужно,
# чтобы обкатать шаблон, не показывая рабочим менеджерам; тестеру это как раз
# по профилю. Переключает флаг только admin (CAN_MANAGE_TEMPLATES).
SEES_HIDDEN_TEMPLATES = (ADMIN, DIRECTOR, TESTER)
