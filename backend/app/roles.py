"""
Канонические роли пользователей (этап 6, брейншторм ролей).

  ADMIN        — полный доступ: пользователи и роли, шаблоны, контрагенты
                 (включая удаление), импорт/экспорт, audit_log, вся история
                 генерации.
  DIRECTOR     — как MANAGER, плюс правка карточек контрагентов, экспорт в
                 Excel, просмотр audit_log, вся история генерации и ПРОСМОТР
                 вкладки "Пользователи" (только видит список и роли — НЕ
                 создаёт, не правит, роли не меняет: это осталось за Admin).
                 НЕТ: импорта, управления шаблонами, удаления контрагентов.
  TOP_MANAGER  — как MANAGER, плюс правка карточек контрагентов и СВОЯ история
                 генерации (только свои документы). БЕЗ экспорта, без audit_log;
                 шаблоны с пометкой "скрыт" не видит.
  TESTER       — как MANAGER, плюс правка карточек контрагентов, кнопка
                 "Тестовые данные" в форме (заполнить демо-значениями в один
                 клик) и просмотр СКРЫТЫХ шаблонов — всё для обкатки шаблонов.
                 БЕЗ экспорта и без истории генерации. Кнопка демо — чисто
                 UX-ная (см. canFillDemoData в permissions.js: серверной
                 проверки нет, демо-данные не привилегия). Самостоятельная
                 роль: раньше повторяла TOP_MANAGER, теперь их права разошлись
                 (у тестера — скрытые шаблоны и демо, у топ-менеджера — своя
                 история генерации), общей зависимости между ними больше нет.
  MANAGER      — рабочая роль: генерация документов, создание контрагентов.
                 Без РЕДАКТИРОВАНИЯ уже заведённых карточек, без удаления,
                 без импорта/экспорта, без шаблонов, без audit_log.

ROLES — единственный источник правды, как COUNTRIES/CONTRAGENT_TYPES в
app/tags.py: любая новая роль добавляется здесь и сразу используется во
всех проверках require_role(...) по всему коду.

Роль хранится в users.role как обычный varchar(16) — ограничения на уровне
БД нет, проверка только здесь (_validate_role в routers_auth.py сверяет с
ROLES). Поэтому новая роль НЕ требует миграции; следить надо лишь за тем,
чтобы её строковое значение влезло в 16 символов.
"""
ADMIN = "admin"
DIRECTOR = "director"
TOP_MANAGER = "top_manager"
TESTER = "tester"
MANAGER = "manager"

ROLES = (ADMIN, DIRECTOR, TOP_MANAGER, TESTER, MANAGER)

# Общие сокращения для Depends(require_role(...)) в роутерах — чтобы не
# перечислять одни и те же тройки/пары ролей в каждом файле по-разному.
ANY_ROLE = ROLES                              # любой залогиненный пользователь
# Экспорт контрагентов и просмотр audit_log раньше делили одну константу
# (CAN_EXPORT), пока обе роли с доступом к экспорту совпадали с ролями с
# доступом к audit_log. С появлением TOP_MANAGER (экспорт есть, audit_log
# нет) это перестало быть верным — разделены на две константы.
CAN_EXPORT_CONTRAGENTS = (ADMIN, DIRECTOR)  # экспорт в Excel (у top_manager/tester убран)
CAN_VIEW_AUDIT_LOG = (ADMIN, DIRECTOR)                    # просмотр audit_log
# Доступ к вкладке "История генерации" (эндпоинты /generation-history).
# Вкладка есть у ВСЕХ ролей (по просьбе владельца 08.08.2026): каждый должен
# видеть СВОЮ генерацию. Разница только в ОБЪЁМЕ: admin/director видят всё
# (SEES_ALL_GENERATION_HISTORY), остальные (top_manager/tester/manager) — только
# свои документы, сервер жёстко ограничивает выдачу их user_id (см. ниже и
# routers_generation_history.py). Поэтому здесь = ROLES, а не перечисление.
CAN_VIEW_GENERATION_HISTORY = ROLES
# Кто видит историю ВСЕХ пользователей. Остальные из CAN_VIEW_GENERATION_HISTORY
# (top_manager/tester/manager) видят и пересоздают лишь свои записи. Ограничение
# серверное, а не UX: без него любой из них по filter_type=user или прямым
# entry_id мог бы дотянуться до чужих документов.
SEES_ALL_GENERATION_HISTORY = (ADMIN, DIRECTOR)
# Удаление записей истории генерации — только Admin (чистка тестовых записей).
CAN_DELETE_GENERATION_HISTORY = (ADMIN,)
CAN_IMPORT = (ADMIN,)               # импорт контрагентов — только Admin
# Вкладка "Пользователи" разведена на два права:
#   VIEW   — видеть список пользователей и их роли (Admin + Director);
#   MANAGE — создавать, править, деактивировать, менять роли (только Admin).
# Director добавлен в просмотр по просьбе владельца, но роли НЕ меняет —
# управление осталось за Admin (эндпоинты create_user/update_user).
CAN_VIEW_USERS = (ADMIN, DIRECTOR)
CAN_MANAGE_USERS = (ADMIN,)
CAN_MANAGE_TEMPLATES = (ADMIN,)
CAN_DELETE_CONTRAGENTS = (ADMIN,)
# Вкладка "Уведомления": НАПИСАТЬ команде (см. app/models.py: Announcement).
# Только Admin — это рассылка на всех сотрудников. ЧИТАТЬ свои уведомления
# может любой залогиненный, отдельного права на это нет: эндпоинты чтения
# отдают строки текущего пользователя и ничьи больше.
CAN_SEND_NOTIFICATIONS = (ADMIN,)

# ML FINANCE — второй продукт в том же приложении: балансы контрагентов,
# поступления и расходы. Переключатель продуктов в шапке (нажатие на «ML Docs»
# слева) и все его экраны — у Admin и Director.
#
# Почему у директора: он и так видит по чтению почти всё (журнал действий,
# вся история генерации, список сотрудников), а деньги по контрагентам —
# ровно его предмет. Менеджеру переключатель не показывается вовсе: для него
# второго продукта не существует.
CAN_USE_FINANCE = (ADMIN, DIRECTOR)
# Вносить поступления и расходы — тоже оба (решение владельца 16.09.2026).
CAN_ADD_FINANCE_OPERATIONS = (ADMIN, DIRECTOR)
# А УДАЛЯТЬ — только Admin. Правки операции нет вовсе: ошибочную удаляют и
# вносят заново, и это осознанно — «исправленная» строка в денежной истории
# не оставляет следа, а удалённая хотя бы исчезает целиком и на глазах.
CAN_DELETE_FINANCE_OPERATIONS = (ADMIN,)

# Номенклатура — каталог треков лейбла. Пока совпадает с CAN_USE_FINANCE, но
# ЗАВЕДЕНА ОТДЕЛЬНО НАМЕРЕННО: каталог наполняет импорт, и импортировать
# треки, скорее всего, будет не тот человек, которому положено видеть суммы
# выплат. Когда такой появится, право расходится в одну строку, а не
# вычленяется задним числом из финансов.
CAN_VIEW_NOMENCLATURE = (ADMIN, DIRECTOR)
# Выгрузить каталог в Excel — оба, как и экспорт контрагентов.
CAN_EXPORT_NOMENCLATURE = (ADMIN, DIRECTOR)
# А ЗАЛИТЬ — только Admin, как и импорт контрагентов: загрузка данных внутрь
# меняет каталог целиком, и цена ошибки тут выше, чем у чтения. Отдельное
# право на импорт треков для человека, который заливает ежедневную выгрузку и
# не должен видеть суммы выплат, появится здесь же — это его место.
CAN_IMPORT_NOMENCLATURE = (ADMIN,)
# ПРАВКА КАРТОЧКИ ТРЕКА РУКАМИ — Admin и Director (17.09.2026). Шире импорта
# намеренно: файл переписывает состав прав у сотен треков разом и вслепую, а
# карточку правят по одной, глядя на неё, и сверка долей со справочными не
# даёт сохранить несходящееся. Это ближе к правке карточки контрагента,
# которая у директора есть, чем к заливке файла, которой у него нет.
CAN_EDIT_NOMENCLATURE = (ADMIN, DIRECTOR)

# Партнёры — справочник площадок, от которых приходят деньги. Смотрят те же,
# кто видит ML Finance; ведут — они же. Импорт здесь НЕ сужен до админа, в
# отличие от контрагентов и номенклатуры: там файл несёт сотни полей и
# перезаписывает карточки, а тут одна колонка с названиями, и цена ошибки —
# лишняя строка в списке, которую видно сразу.
CAN_VIEW_PARTNERS = (ADMIN, DIRECTOR)
CAN_MANAGE_PARTNERS = (ADMIN, DIRECTOR)

# Отчёты площадок: загрузка файлов и правила их разбора (18.09.2026). Право
# своё, хоть пока и совпадает с финансовым: отчёт — это деньги площадки до
# дележа, и однажды его может грузить человек, которому не положено видеть
# балансы правообладателей. Разойтись им проще одной строкой, чем выковыривать
# загрузку из финансов задним числом — та же причина, что у номенклатуры.
CAN_VIEW_PARTNER_REPORTS = (ADMIN, DIRECTOR)
CAN_MANAGE_PARTNER_REPORTS = (ADMIN, DIRECTOR)

# Поступления от площадок: деньги, которые пришли на счёт (19.09.2026).
#
# Право СВОЁ, хоть пока и совпадает с отчётами: отчёт — это что площадка
# насчитала, а поступление — что реально дошло до счёта, вместе с курсом и
# заводом валюты. Смотреть первое и второе однажды будут разные люди, и
# разойтись правам проще одной строкой, чем выковыривать поступления из
# отчётов задним числом.
CAN_VIEW_PAYMENTS = (ADMIN, DIRECTOR)
CAN_MANAGE_PAYMENTS = (ADMIN, DIRECTOR)

# Вкладка «Кубок»: кто носит кубок месяца и рейтинг текущего месяца.
#
# У ВСЕХ ролей (16.09.2026, решение владельца). Раньше была только у Admin —
# по тому же основанию, что журнал действий: сводка по работе всех сотрудников
# сразу. Основание отпало: соревнование, которого не видят соревнующиеся, не
# соревнование, а доска НЕ показывает чисел — только порядок мест и шкалу
# относительно лидера (см. ChampionPage), так что выработка конкретного
# человека наружу по-прежнему не уходит.
#
# = ROLES, а не перечисление: доска общая для всех, и новая роль должна
# видеть её сама собой. Не путать с COMPETING_ROLES в champion.py — ТАМ
# список перечислительный (менеджеры и топ-менеджеры), и новая роль в зачёт
# сама не попадёт. Видеть доску и участвовать в ней — разные вещи.
CAN_VIEW_CHAMPION_BOARD = ROLES

# Вкладка «Dista Connect»: сверка нашей базы контрагентов с выгрузкой из Dista
# Music (проставить связку dista_id, завести новых из Dista). Только Admin —
# это операция над всей базой контрагентов (создание карточек, изменение
# связки), по аналогии с импортом/уведомлениями.
CAN_USE_DISTA_SYNC = (ADMIN,)

# Генерация документов и создание контрагентов — рабочие действия, доступные
# ВСЕМ ролям, включая те, что появятся в будущем. Поэтому здесь = ROLES, а не
# перечисление поимённо.
#
# ЭТО НЕ ПРИДИРКА К СТИЛЮ. Оба кортежа раньше перечисляли роли вручную, и
# оба молча ломались при добавлении новой: TESTER 17.07.2026 не смог
# сгенерировать документ именно потому, что CAN_GENERATE перечислял четыре
# роли и про пятую не знал. Комментарий рядом при этом честно гласил
# "доступно всем ролям" — то есть намерение и код разошлись, а поймал это
# только пользователь на проде. С `= ROLES` разойтись уже нечему.
CAN_GENERATE = ROLES
CAN_CREATE_CONTRAGENTS = ROLES

# Редактирование существующей карточки. В обычном режиме — НЕ для Manager:
# он заводит новых контрагентов и генерирует по ним документы, а правка уже
# заведённой карточки остаётся за Admin/Director/TopManager/Tester.
#
# ⚠️ ВРЕМЕННО (04.08.2026): на период МАССОВОГО ЗАПОЛНЕНИЯ базы менеджерам
# открыты ВСЕ поля карточки (а не только тип договора/реквизиты/рег.номер/
# псевдонимы). Как только менеджеры закончат заполнение — «закрыть обратно»:
# вернуть кортеж к (ADMIN, DIRECTOR, TOP_MANAGER, TESTER) и зеркально поправить
# permissions.js (canEditContragents). Это ЕДИНСТВЕННЫЕ две строки отката —
# поле-guard в update_contragent и restricted-режим модалки трогать не нужно,
# они снова включатся сами, как только manager выйдет из этого кортежа.
CAN_EDIT_CONTRAGENTS = ROLES

# Тип договора (contract_family) карточки может менять ЛЮБАЯ роль, включая
# manager — по просьбе владельца: менеджеру нужно уметь переключить тип
# договора контрагента (от него зависит подбор документов), но НЕ трогать
# остальные поля карточки. Поэтому эндпоинт update_contragent доступен всем
# этим ролям, но тем, кого нет в CAN_EDIT_CONTRAGENTS (сейчас — manager),
# разрешено передать ТОЛЬКО contract_family (и requisites, см. ниже); любое
# другое поле → 403.
CAN_EDIT_CONTRACT_FAMILY = ROLES

# Реквизиты карточки (requisites — адреса, банк, паспорт СГ и т.п.) может
# править ЛЮБАЯ роль, включая manager (по просьбе владельца): реквизиты — не
# идентификатор и не привилегия, их дозаполняют по ходу работы. Как и с
# contract_family, поле-уровневая проверка в update_contragent пропускает
# requisites даже для тех, кого нет в CAN_EDIT_CONTRAGENTS, а остальные поля
# им по-прежнему запрещены.
CAN_EDIT_REQUISITES = ROLES

# Рег. номер (ИНН/ОГРНИП/ОГРН/БИН) правит ЛЮБАЯ роль (по просьбе владельца
# 04.08.2026): он показан в блоке реквизитов карточки «всё в одном месте», и
# менеджер дозаполняет его там наравне с остальными реквизитами. Это ослабление
# прежнего правила (раньше рег. номер был только у CAN_EDIT_CONTRAGENTS): его
# уникальность/длину по-прежнему валидирует сервер (normalize_reg_number +
# проверка конфликта в update_contragent), так что «испортить» идентификатор
# кривым вводом нельзя — только заменить на другой валидный.
CAN_EDIT_REG_NUMBER = ROLES

# Номер договора (contract_number) карточки правит ЛЮБАЯ роль, включая manager
# (по просьбе владельца 08.08.2026): у части карточек номер пуст, и его
# дозаполняют по ходу работы — как рег.номер/реквизиты. Это ручной override, а
# НЕ пересчёт по формуле (build_contract_number при правке не запускается, см.
# update_contragent). Поле-guard пропускает contract_number для всех ролей,
# прочие поля менеджеру по-прежнему закрыты. Держится отдельно от временного
# CAN_EDIT_CONTRAGENTS=ROLES: даже когда тот вернут к списку без manager, право
# на номер договора у менеджера сохранится.
CAN_EDIT_CONTRACT_NUMBER = ROLES

# Титл карточки правит ТОЛЬКО admin (по просьбе владельца 11.08.2026). Проверка
# в update_contragent отдельная и НЕ зависит от CAN_EDIT_CONTRAGENTS (даже когда
# тот временно = ROLES и менеджерам открыта вся карточка — титл всё равно только
# админу). На фронте поле «Титл» показывается только админу (canEditTitle).
CAN_EDIT_TITLE = (ADMIN,)

# Псевдонимы карточки правит ЛЮБАЯ роль, включая manager (по просьбе владельца):
# менеджер работает с псевдонимами при генерации, ему удобно поправить их прямо
# в карточке. Как и contract_family/requisites/reg_number — поле-guard в
# update_contragent пропускает nicknames для всех ролей, прочие поля менеджеру
# по-прежнему закрыты.
CAN_EDIT_NICKNAMES = ROLES

# Кто видит шаблоны, помеченные "скрыт для менеджеров" (hidden_for_managers):
# admin/director/tester. У top_manager видимость скрытых убрана (по просьбе
# владельца) — по этому праву он теперь как обычный manager. Скрытие нужно,
# чтобы обкатать шаблон, не показывая рабочим менеджерам; тестеру это как раз
# по профилю. Переключает флаг только admin (CAN_MANAGE_TEMPLATES).
SEES_HIDDEN_TEMPLATES = (ADMIN, DIRECTOR, TESTER)
