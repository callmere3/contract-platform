"""
Сведение имени плательщика из выписки к площадке справочника.

ЗАЧЕМ. В банковской выписке плательщик записан полным юридическим именем —
«ПАО "МТС"», «ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "101 И К"», «ООО "ЗИОН
МЬЮЗИК" Р/С 40702810…», — а в справочнике площадка называется коротко: «МТС»,
«101 и К», «ЗИОН МЬЮЗИК». Импорт, сверяющий строки буква в букву, узнавал одну
площадку из 69 (просьба владельца 23.09.2026 — «нужно чтобы все существующие
в базе партнёры правильно привязались»).

ЧЕТЫРЕ СПОСОБА, В ЭТОМ ПОРЯДКЕ. Каждый следующий слабее предыдущего, и любой
срабатывает, только если ответ ЕДИНСТВЕННЫЙ: привязать деньги к чужой площадке
хуже, чем оставить строку подписанной текстом.

  1. Точное совпадение очищенных имён.
  2. Имя справочника целым словом внутри имени из выписки: «ЗИОН МЬЮЗИК»
     находится в «ЗИОН МЬЮЗИК ПЛЮС».
  3. Аббревиатура: «Российское Авторское Общество» → РАО, «Всероссийская
     Организация Интеллектуальной Собственности» → ВОИС. Только для коротких
     заглавных имён справочника — иначе под правило попадёт что угодно.
  4. Не нашлось — возвращаем ОЧИЩЕННОЕ имя, чтобы в таблице стояло «Муз ТВ
     Операционная компания», а не «ООО "Муз ТВ Операционная компания" Р/С
     40702810900000001234».

ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: похожести по опечаткам. В номенклатуре она уместна
— там человек подтверждает замену глазами, — а тут строка уходит в деньги.
"""
import re

# Формы собственности и прочий шум, который в имени площадки не значит ничего.
LEGAL_FORMS = (
    "публичное акционерное общество",
    "закрытое акционерное общество",
    "открытое акционерное общество",
    "общество с ограниченной ответственностью",
    "акционерное общество",
    "индивидуальный предприниматель",
    "товарищество с ограниченной ответственностью",
    "непубличное акционерное общество",
    "ороо", "нко", "пао", "оао", "зао", "тоо", "ооо", "ао", "ип",
    "inc", "llc", "ltd", "limited", "corp", "gmbh", "b.v.", "bv", "s.a.",
)
# Хвост с банковскими реквизитами: «Р/С 40702810…», «ИНН …», «КПП …».
#
# МАРКЕР ОБЯЗАН СТОЯТЬ ОТДЕЛЬНЫМ СЛОВОМ, и у счёта обязательна косая черта.
# Без этого «кс» находилось внутри слов: «Янде|кс| Музыка» превращалось в
# «Янде», а «ООО "О|КС|"» — в «О». Ошибка тихая: имя молча укорачивалось, и
# площадка потом привязывалась к чужой.
TAIL = re.compile(
    r"(?:^|[\s,])\s*(р\s*/\s*с|к\s*/\s*с|инн|кпп|бик|расч[её]тный\s+сч[её]т)\b.*$",
    re.IGNORECASE,
)
# ИМЕНА, КОТОРЫЕ НЕ СВЕСТИ НИКАКОЙ ОЧИСТКОЙ. Плательщик в выписке и площадка у
# нас — разные юридические лица: деньги за YouTube приходят от CHOIS MUSIC,
# INC (владелец, 23.09.2026). Из одного имени другое не выводится ничем, кроме
# знания, поэтому оно записано здесь явно.
#
# В КОДЕ, А НЕ СТРОКОЙ В БАЗЕ — по той же причине, что встроенные правила
# отчётов площадок: правило, однажды записанное в базу, живёт там вечно и
# расходится с тем, что написано здесь. Ключ слева — очищенное имя из выписки,
# справа — очищенное имя площадки справочника.
ALIASES = {
    "chois music inc": "youtube",
}

IN_BRACKETS = re.compile(
    r"\s*\(\s*(ооо|оао|пао|зао|ао|ип|тоо|ороо|llc|ltd|inc)\s*\)\s*", re.IGNORECASE
)
QUOTES = '"«»“”„`\''


def clean_name(raw: str) -> str:
    """
    Имя для показа: без формы собственности, кавычек и реквизитов.

    Регистр НЕ трогаем: в выписке встречается и «101 И К», и «Муз ТВ», и
    приводить одно к другому — значит решать за человека, как называется
    компания.
    """
    text = " ".join(str(raw or "").split())
    if not text:
        return ""
    text = TAIL.sub("", text)
    # Форма в скобках — так записаны сами площадки справочника: «Ворнер
    # (ООО)», «Феникс мьюзик (ООО)». Без этого они не сходятся с «ООО "ВОРНЕР
    # МЬЮЗИК"» из выписки, хотя это одна и та же компания.
    text = IN_BRACKETS.sub("", text).strip()
    changed = True
    while changed:                       # «ООО ТОО …» — редко, но встречается
        changed = False
        low = text.lower()
        for form in LEGAL_FORMS:
            for pattern in (form + " ", form + '"', form + "«"):
                if low.startswith(pattern):
                    text = text[len(form):].lstrip(" " + QUOTES)
                    changed = True
                    break
            if changed:
                break
    # В выписке попадаются «имена» на полторы сотни знаков — вместе с адресом
    # банка и номером платежа. Столбец такое не покажет, а в базе оно мешает.
    return text.strip(" ,." + QUOTES)[:120].strip(" ,." + QUOTES)


def _key(name: str) -> str:
    """Ключ сравнения: без кавычек, регистра, «ё» и лишних пробелов."""
    text = clean_name(name).lower().replace("ё", "е")
    text = re.sub(r"[%s]" % re.escape(QUOTES), " ", text)
    text = re.sub(r"[^\w\s]", " ", text, flags=re.UNICODE)
    return " ".join(text.split())


def _acronym(name: str) -> str:
    """«Российское Авторское Общество» → «рао». Пустая строка, если не вышло."""
    words = [w for w in _key(name).split() if len(w) > 2]
    return "".join(w[0] for w in words) if len(words) >= 2 else ""


class PartnerIndex:
    """Справочник площадок, подготовленный к сопоставлению."""

    def __init__(self, partners):
        """partners: последовательность (id, name)."""
        self.by_key: dict = {}
        self.words: list = []
        self.by_acronym: dict = {}
        seen_acronym: dict = {}
        for partner_id, name in partners:
            key = _key(name)
            if not key:
                continue
            # Одинаковые ключи (['ОКС', 'окс']) делают выбор неоднозначным —
            # такую площадку не подставляем вовсе.
            self.by_key[key] = None if key in self.by_key else partner_id
            self.words.append((key, partner_id))
            short = key.replace(" ", "")
            if 2 <= len(short) <= 5 and name.upper() == name:
                seen_acronym[short] = None if short in seen_acronym else partner_id
        self.by_acronym = seen_acronym

    def match(self, raw: str):
        """Площадка справочника или None. Неоднозначность — тоже None."""
        key = _key(raw)
        if not key:
            return None

        # Известная связка проверяется ПЕРВОЙ: она сильнее любого совпадения
        # по тексту, потому что опирается на знание, а не на похожесть имён.
        alias = ALIASES.get(key)
        if alias:
            return self.by_key.get(alias)

        found = self.by_key.get(key)
        if found:
            return found

        # Имя справочника целым словом внутри имени из выписки.
        inside = {
            partner_id
            for other, partner_id in self.words
            if partner_id and len(other) >= 3 and re.search(
                r"(?:^|\s)%s(?:\s|$)" % re.escape(other), key
            )
        }
        if len(inside) == 1:
            return next(iter(inside))
        if inside:
            return None                  # подошло несколько — не выбираем

        short = self.by_acronym.get(_acronym(raw))
        return short or None
