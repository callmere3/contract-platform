"""
Признак «действие пришло из интерфейса», а не из скрипта на сервере.

ЗАЧЕМ. Журнал действий (audit_log) заполняется вызовами log_action прямо из
функций-роутеров. Ровно эти же функции дёргают отладочные и E2E-скрипты
внутри контейнера (`docker compose exec api python ...`), и их правки
ложились в журнал неотличимо от работы живого человека. Разбор 10.09.2026
показал масштаб: 69 записей из 241 (29%) — прогоны тестов, включая две
«правки карточек», числившиеся за учёткой менеджера, который в те дни в
систему вообще не входил. Журнал, где четверть записей — выдумка, нельзя
показывать как ответ на вопрос «кто это сделал».

КАК ОТЛИЧАЕМ. Любой HTTP-запрос проходит через мидлварь ниже, и она на
время запроса поднимает флаг в ContextVar. Скрипт вызывает функции
напрямую — мидлвари в его пути исполнения просто нет, флаг остаётся
опущенным.

ПОЧЕМУ ContextVar, А НЕ АРГУМЕНТ. log_action вызывается из 14 мест;
протаскивать через все Request — шум. К тому же аргумент скрипт может
передать любой, а мидлварь обойти не может.

ПОЧЕМУ «ЧИСТАЯ» ASGI-МИДЛВАРЬ, А НЕ @app.middleware("http"). Вторая
(BaseHTTPMiddleware) исполняет приложение в отдельной задаче, и выставленный
вокруг вызова ContextVar ведёт себя непредсказуемо. Здесь значение ставится
в той же задаче, что обрабатывает запрос; синхронные эндпоинты FastAPI
уносит в пул потоков с КОПИЕЙ текущего контекста — флаг в копию попадает.

ЧЕГО ЭТО НЕ ДЕЛАЕТ. Не защита от подделки: у того, кто может выполнить код
в контейнере, и так есть прямой доступ к базе. Это отделение тестового шума
от работы людей, а не контроль доступа.
"""
from contextvars import ContextVar

_in_http_request: ContextVar[bool] = ContextVar("in_http_request", default=False)


def in_http_request() -> bool:
    """True, если код исполняется в рамках HTTP-запроса к API."""
    return _in_http_request.get()


class HttpRequestContextMiddleware:
    """Поднимает флаг in_http_request на время обработки HTTP-запроса."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope.get("type") != "http":
            await self.app(scope, receive, send)
            return

        token = _in_http_request.set(True)
        try:
            await self.app(scope, receive, send)
        finally:
            _in_http_request.reset(token)
